import { ExternalLink } from 'lucide-react';
import { Link } from 'react-router';
import { useTranslation } from 'react-i18next';
import { buttonClasses } from '@/components/ui/Button';
import { cn } from '@/lib/cn';
import type { Difference, Evidence } from '@/types/comparison';

const TONE = {
  changed: 'bg-warning-tint text-warning',
  added: 'bg-success-tint text-success',
  removed: 'bg-danger-tint text-danger',
} as const;

function Side({ evidence, documentId, name }: { evidence: Evidence | null; documentId: string; name: string }) {
  const { t } = useTranslation();
  return (
    <div className="min-w-0 rounded-control border border-line bg-card p-3">
      <header className="mb-2 flex items-center justify-between gap-2 text-xs text-muted">
        <span className="min-w-0 truncate" title={name}>{name}</span>
        {evidence?.page != null && <span className="tabular shrink-0 font-medium text-fg">{t('sources.page', { page: evidence.page })}</span>}
      </header>
      {evidence ? (
        <>
          <blockquote className="border-l-2 border-accent-2 pl-3 font-quote text-[15px] leading-[23px] break-words text-fg/90">{evidence.quote}</blockquote>
          {evidence.page != null && (
            <Link
              to={`/documents/${documentId}`}
              state={{ jump: { page: evidence.page, quote: evidence.quote } }}
              className={cn(buttonClasses('secondary', 'sm'), 'mt-3')}
            >
              <ExternalLink size={14} aria-hidden />
              {t('sources.openPage', { page: evidence.page })}
            </Link>
          )}
        </>
      ) : (
        <p className="text-sm text-muted">{t('compare.absent')}</p>
      )}
    </div>
  );
}

interface Props {
  difference: Difference;
  a: { id: string; name: string };
  b: { id: string; name: string };
}

export function DifferenceCard({ difference, a, b }: Props) {
  const { t } = useTranslation();
  return (
    <li data-testid="difference" className="rounded-panel border border-line bg-sidebar p-4">
      <p className="mb-3 flex flex-wrap items-center gap-2 text-sm">
        <span className={cn('rounded-full px-2 text-xs font-medium', TONE[difference.type])}>{t(`compare.type.${difference.type}`)}</span>
        {/* Generated by the backend's diff in English, so it is marked for assistive technology. */}
        <span lang="en" className="min-w-0 break-words text-muted">{difference.explanation}</span>
      </p>
      <div className="grid gap-2 md:grid-cols-2">
        <Side evidence={difference.a} documentId={a.id} name={a.name} />
        <Side evidence={difference.b} documentId={b.id} name={b.name} />
      </div>
    </li>
  );
}
