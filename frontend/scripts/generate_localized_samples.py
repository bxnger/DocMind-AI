def find_fonts() -> tuple[str, str]:
    for regular, bold in FONTS:
        if Path(regular).exists() and Path(bold).exists():
            return regular, bold
    raise SystemExit("No TrueType font with Cyrillic found (Arial or DejaVu Sans).")


def wrap(text: str, font: pymupdf.Font, size: float, width: float) -> list[str]:
    lines, line = [], ""
    for word in text.split(" "):
        trial = f"{line} {word}" if line else word
        if line and font.text_length(trial, size) > width:
            lines.append(line)
            line = word
        else:
            line = trial
    if line:
        lines.append(line)
    return lines


def build(spec: dict, regular_path: str, bold_path: str) -> list[int]:
    """Writes the PDF and returns, for each clause number found, nothing: see the page report below."""
    regular, bold = pymupdf.Font(fontfile=regular_path), pymupdf.Font(fontfile=bold_path)
    doc = pymupdf.open()
    width = PAGE_W - 2 * MARGIN_X
    state = {"page": None, "writer": None, "y": TOP}
    pages_of: dict[str, int] = {}

    def new_page() -> None:
        flush()
        state["page"] = doc.new_page(width=PAGE_W, height=PAGE_H)
        state["writer"] = pymupdf.TextWriter(state["page"].rect)
        state["y"] = TOP

    def flush() -> None:
        if state["page"] is not None:
            state["writer"].write_text(state["page"])  # colors are set per call below, through separate writers

    # One writer per color is needed: collect text runs and draw them in order.
    runs: list[list[tuple]] = []

    def put(x: float, y: float, font: pymupdf.Font, size: float, text: str, color: tuple) -> None:
        runs[-1].append((x, y, font, size, text, color))

    def start_page() -> None:
        runs.append([])
        state["y"] = TOP

    def need(height: float) -> None:
        if state["y"] + height > PAGE_H - BOTTOM:
            start_page()

    start_page()
    for kind, value in spec["content"]:
        if kind == "title":
            state["y"] += 22
            put(MARGIN_X, state["y"], bold, 22, value, TEXT)
            state["y"] += 28 - 22 + 6
        elif kind == "subtitle":
            state["y"] += 12
            put(MARGIN_X, state["y"], regular, 12, value, MUTED)
            state["y"] += 26 - 12 + 4
        elif kind == "note":
            runs[-1].append(("rect", MARGIN_X, state["y"] - 8, 468, 26))
            state["y"] += 9
            put(MARGIN_X + 10, state["y"], regular, 9, value, NOTE_INK)
            state["y"] += 40 - 9
        elif kind == "h":
            need(50)
            state["y"] += 8 + 12.5
            put(MARGIN_X, state["y"], bold, 12.5, value, TEXT)
            state["y"] += 20 - 12.5
        else:
            lines = wrap(value, regular, BODY_SIZE, width)
            need(len(lines) * LEADING + 8)
            number = value.split(" ", 1)[0]
            pages_of[number] = len(runs)
            for line in lines:
                state["y"] += LEADING
                put(MARGIN_X, state["y"] - 4, regular, BODY_SIZE, line, TEXT)
            state["y"] += 7

    total = len(runs)
    for index, page_runs in enumerate(runs, start=1):
        page = doc.new_page(width=PAGE_W, height=PAGE_H)
        for item in page_runs:
            if item[0] == "rect":
                _, x, y, w, h = item
                page.draw_rect(pymupdf.Rect(x, y, x + w, y + h), color=None, fill=NOTE_FILL)
        for item in page_runs:
            if item[0] == "rect":
                continue
            x, y, font, size, text, color = item
            writer = pymupdf.TextWriter(page.rect, color=color)
            writer.append((x, y), text, font=font, fontsize=size)
            writer.write_text(page)
        foot = pymupdf.TextWriter(page.rect, color=FOOT)
        foot.append((MARGIN_X, PAGE_H - 48), spec["footer"], font=regular, fontsize=8.5)
        label = spec["page"].format(n=index, total=total)
        foot.append((PAGE_W - MARGIN_X - regular.text_length(label, 8.5), PAGE_H - 48), label, font=regular, fontsize=8.5)
        foot.write_text(page)
    doc.set_metadata({"title": spec["title_meta"], "producer": "DOCMIND AI sample generator"})
    doc.subset_fonts()
    doc.save(OUT / spec["file"], deflate=True, garbage=3)
    doc.close()
    print(f"{spec['file']}: {total} pages")
    for clause in ("4.3", "9.1", "10.2"):
        print(f"  clause {clause} is on page {pages_of.get(clause)}")
    return [total]


if __name__ == "__main__":
    regular_path, bold_path = find_fonts()
    OUT.mkdir(parents=True, exist_ok=True)
    for spec in (RU, KK):
        build(spec, regular_path, bold_path)
    sys.exit(0)
